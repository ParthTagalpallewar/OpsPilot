"""Persist local replay investigations, jobs, and approvals."""

import json
from collections.abc import Callable
from datetime import UTC, datetime
from pathlib import Path
from sqlite3 import Connection
from time import time
from uuid import uuid4

from opentelemetry.trace.propagation.tracecontext import TraceContextTextMapPropagator

from opspilot.approval_graph import pause_review, resolve_review
from opspilot.approvals import ApprovalConflict, make_plan
from opspilot.checkpoints import setup_checkpoints
from opspilot.replay import SCENARIOS, investigate
from opspilot.storage import InvestigationDatabase, PostgresConnection
from opspilot.telemetry import tracer

propagator = TraceContextTextMapPropagator()


class InvestigationStore:
    def __init__(
        self,
        database: Path | str,
        captures: Path,
        *,
        on_enqueue: Callable[[], None] | None = None,
        checkpoint_replay: bool = False,
    ):
        self.database = InvestigationDatabase(database)
        self.captures = captures
        self.on_enqueue = on_enqueue
        self.checkpoint_dsn = (
            database if checkpoint_replay and isinstance(database, str) else None
        )
        if isinstance(database, str):
            setup_checkpoints(database)
        postgres = self.database.postgres
        sequence = "BIGINT GENERATED BY DEFAULT AS IDENTITY" if postgres else "INTEGER"
        enqueue_order = (
            ", enqueue_order BIGINT GENERATED ALWAYS AS IDENTITY" if postgres else ""
        )
        lease = "DOUBLE PRECISION" if postgres else "REAL"
        with self.database.session(write=True) as connection:
            connection.execute("""
                CREATE TABLE IF NOT EXISTS investigations (
                    id TEXT PRIMARY KEY,
                    document TEXT NOT NULL
                )
            """)

            connection.execute("""
                CREATE TABLE IF NOT EXISTS approval_events (
                    investigation_id TEXT NOT NULL,
                    sequence INTEGER NOT NULL,
                    event TEXT NOT NULL,
                    PRIMARY KEY (investigation_id, sequence)
                )
            """)

            connection.execute(f"""
                CREATE TABLE IF NOT EXISTS replay_jobs (
                    investigation_id TEXT PRIMARY KEY,
                    scenario TEXT NOT NULL,
                    claim_token TEXT,
                    lease_until {lease}{enqueue_order}
                )
            """)

            connection.execute("""
                CREATE TABLE IF NOT EXISTS alert_occurrences (
                    occurrence TEXT PRIMARY KEY,
                    investigation_id TEXT NOT NULL
                )
            """)
            connection.execute("""
                CREATE TABLE IF NOT EXISTS replay_job_trace (
                    investigation_id TEXT PRIMARY KEY,
                    carrier TEXT NOT NULL
                )
            """)
            connection.execute(f"""
                CREATE TABLE IF NOT EXISTS investigation_events (
                    sequence {sequence} PRIMARY KEY,
                    investigation_id TEXT NOT NULL,
                    status TEXT NOT NULL,
                    recorded_at TEXT NOT NULL,
                    step TEXT
                )
            """)
            if not postgres:
                columns = {
                    row[1]
                    for row in connection.execute(
                        "PRAGMA table_info(investigation_events)"
                    )
                }
                if "step" not in columns:
                    connection.execute(
                        "ALTER TABLE investigation_events ADD COLUMN step TEXT"
                    )
            connection.execute("""
                CREATE INDEX IF NOT EXISTS investigation_event_cursor
                ON investigation_events (investigation_id, sequence)
            """)

    @staticmethod
    def _record_status(
        connection: Connection | PostgresConnection, document: dict
    ) -> None:
        connection.execute(
            "INSERT INTO investigation_events (investigation_id, status, recorded_at) "
            "VALUES (?, ?, ?)",
            (
                document["investigation_id"],
                document["status"],
                datetime.now(UTC).isoformat(),
            ),
        )

    def events_after(self, investigation_id: str, cursor: int) -> list[dict]:
        with self.database.session() as connection:
            rows = connection.execute(
                "SELECT sequence, status, recorded_at, step FROM investigation_events "
                "WHERE investigation_id = ? AND sequence > ? "
                "ORDER BY sequence LIMIT 100",
                (investigation_id, cursor),
            ).fetchall()
        return [
            {
                "id": sequence,
                "status": status,
                "recorded_at": recorded_at,
                **({"step": step} if step is not None else {}),
            }
            for sequence, status, recorded_at, step in rows
        ]

    @tracer.start_as_current_span(
        "opspilot.incident.accept",
        record_exception=False,
        set_status_on_exception=False,
    )
    def create(
        self,
        scenario: str,
        title: str,
        description: str,
        *,
        queued: bool = False,
        as_of: datetime | None = None,
        alert_occurrence: str | None = None,
    ) -> dict:
        if scenario not in SCENARIOS:
            raise ValueError(f"Unknown replay scenario: {scenario}")
        title, description = title.strip(), description.strip()
        if not title or not description:
            raise ValueError("Title and description are required")

        document = {
            "investigation_id": str(uuid4()),
            "incident_id": str(uuid4()),
            "title": title,
            "description": description,
            "created_at": datetime.now(UTC).isoformat(),
            "status": "queued",
            "report": None,
        }
        if as_of is not None:
            if as_of.utcoffset() is None:
                raise ValueError("Replay cutoff requires a UTC offset")
            document["as_of"] = as_of.astimezone(UTC).isoformat()
        if not queued:
            self._complete(document, investigate(scenario, self.captures, as_of=as_of))
        with self.database.session(write=True) as connection:
            if alert_occurrence is not None:
                existing = connection.execute(
                    "SELECT investigation_id FROM alert_occurrences "
                    "WHERE occurrence = ?",
                    (alert_occurrence,),
                ).fetchone()
                if existing:
                    return self._load(connection, existing[0])
                connection.execute(
                    "INSERT INTO alert_occurrences VALUES (?, ?)",
                    (alert_occurrence, document["investigation_id"]),
                )
                document["source"] = "alertmanager"
            if document.get("plan"):
                pause_review(connection, document["plan"])
            connection.execute(
                "INSERT INTO investigations (id, document) VALUES (?, ?)",
                (document["investigation_id"], json.dumps(document)),
            )
            self._record_status(connection, document)
            if queued:
                connection.execute(
                    "INSERT INTO replay_jobs (investigation_id, scenario) "
                    "VALUES (?, ?)",
                    (document["investigation_id"], scenario),
                )
                carrier: dict[str, str] = {}
                propagator.inject(carrier)
                if carrier:
                    connection.execute(
                        "INSERT INTO replay_job_trace VALUES (?, ?)",
                        (document["investigation_id"], json.dumps(carrier)),
                    )
        if queued and self.on_enqueue is not None:
            self.on_enqueue()
        return document

    @staticmethod
    def _complete(document: dict, report: dict) -> None:
        document.update(status="completed", report=report)
        hypothesis = report["hypothesis"]
        if hypothesis:
            document["plan"] = make_plan(
                hypothesis["recommended_check"],
                hypothesis["evidence_ids"],
                datetime.now(UTC),
            )
            document["approval_status"] = "awaiting_approval"

    @staticmethod
    def _save(connection: Connection | PostgresConnection, document: dict) -> None:
        connection.execute(
            "UPDATE investigations SET document = ? WHERE id = ?",
            (json.dumps(document), document["investigation_id"]),
        )

    def _record_step(self, investigation_id: str, token: str, step: str) -> None:
        with self.database.session(write=True) as connection:
            connection.execute(
                "INSERT INTO investigation_events "
                "(investigation_id, status, recorded_at, step) "
                "SELECT investigation_id, 'running', ?, ? FROM replay_jobs "
                "WHERE investigation_id = ? AND claim_token = ?",
                (datetime.now(UTC).isoformat(), step, investigation_id, token),
            )

    def process_next(self) -> bool:
        token = str(uuid4())
        with self.database.session(write=True) as connection:
            now = time()
            job = connection.execute(
                "SELECT investigation_id, scenario FROM replay_jobs "
                "WHERE lease_until IS NULL OR lease_until <= ? "
                f"ORDER BY {self.database.job_order} LIMIT 1",
                (now,),
            ).fetchone()
            if job is None:
                return False
            investigation_id, scenario = job
            carrier = connection.execute(
                "SELECT carrier FROM replay_job_trace WHERE investigation_id = ?",
                (investigation_id,),
            ).fetchone()
            connection.execute(
                "UPDATE replay_jobs SET claim_token = ?, lease_until = ? "
                "WHERE investigation_id = ?",
                (token, now + 60, investigation_id),
            )
            document = self._load(connection, investigation_id)
            document["status"] = "running"
            self._save(connection, document)
            self._record_status(connection, document)

        with tracer.start_as_current_span(
            "opspilot.worker.run",
            context=propagator.extract(json.loads(carrier[0]) if carrier else {}),
            attributes={"opspilot.investigation_id": investigation_id},
            record_exception=False,
            set_status_on_exception=False,
        ) as span:
            try:
                report = investigate(
                    scenario,
                    self.captures,
                    as_of=datetime.fromisoformat(document["as_of"])
                    if "as_of" in document
                    else None,
                    checkpoint=(self.checkpoint_dsn, investigation_id)
                    if self.checkpoint_dsn
                    else None,
                    on_step=lambda step: self._record_step(
                        investigation_id, token, step
                    ),
                )
                self._complete(document, report)
            except (OSError, ValueError):
                document.update(
                    status="failed", error="Replay telemetry is unavailable"
                )
            span.set_attribute("opspilot.outcome", document["status"])

        with self.database.session(write=True) as connection:
            matched = connection.execute(
                "DELETE FROM replay_jobs "
                "WHERE investigation_id = ? AND claim_token = ?",
                (investigation_id, token),
            ).rowcount
            if matched:
                connection.execute(
                    "DELETE FROM replay_job_trace WHERE investigation_id = ?",
                    (investigation_id,),
                )
                if document.get("plan"):
                    pause_review(connection, document["plan"])
                self._save(connection, document)
                self._record_status(connection, document)
        return True

    def get(self, investigation_id: str) -> dict | None:
        with self.database.session() as connection:
            return self._load(connection, investigation_id)

    @staticmethod
    def _load(
        connection: Connection | PostgresConnection, investigation_id: str
    ) -> dict | None:
        row = connection.execute(
            "SELECT document FROM investigations WHERE id = ?", (investigation_id,)
        ).fetchone()
        if row is None:
            return None
        document = json.loads(row[0])
        events = [
            json.loads(event)
            for (event,) in connection.execute(
                "SELECT event FROM approval_events WHERE investigation_id = ? "
                "ORDER BY sequence",
                (investigation_id,),
            )
        ]
        if events:
            document["approval_status"] = events[-1]["status"]
            for event in events:
                if event["replacement_plan"]:
                    document["plan"] = event["replacement_plan"]
            document["approval_history"] = events
            preview = events[-1].get("dry_run_preview")
            if preview is not None:
                document["dry_run_preview"] = preview
        return document

    def review(
        self, investigation_id: str, review: dict, *, reviewer: str = "local"
    ) -> dict | None:
        with self.database.session(write=True) as connection:
            document = self._load(connection, investigation_id)
            if document is None:
                return None
            history = document.get("approval_history", [])
            if (
                history
                and history[-1]["review"] == review
                and history[-1].get("reviewer", "local") == reviewer
            ):
                return document

            plan = document.get("plan")
            if document.get("approval_status") != "awaiting_approval" or plan is None:
                raise ApprovalConflict("No plan is awaiting approval")
            if any(plan[key] != review[key] for key in ("plan_id", "plan_hash")):
                raise ApprovalConflict("Review does not match the active plan")
            now = datetime.now(UTC)
            if now >= datetime.fromisoformat(plan["expires_at"]):
                raise ApprovalConflict("The plan has expired")

            decision = review["decision"]
            preview = resolve_review(connection, plan, decision)
            replacement = None
            status = {
                "approve": "approved",
                "reject": "rejected",
                "edit": "awaiting_approval",
            }
            if decision == "edit":
                replacement = make_plan(review["edits"], plan["evidence_ids"], now)
                pause_review(connection, replacement)
            event = {
                "review": review,
                "reviewer": reviewer,
                "reviewed_at": now.isoformat(),
                "status": status[decision],
                "reviewed_plan": plan,
                "replacement_plan": replacement,
            }
            if preview is not None:
                event["dry_run_preview"] = preview
            connection.execute(
                "INSERT INTO approval_events VALUES (?, ?, ?)",
                (investigation_id, len(history) + 1, json.dumps(event)),
            )
            return self._load(connection, investigation_id)
